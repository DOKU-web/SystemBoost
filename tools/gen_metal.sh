#!/usr/bin/env bash
# Generates Metal shaders for the macOS engine from the same HLSL used on
# Windows (HLSL -> SPIR-V with glslang -> MSL with SPIRV-Cross), so both
# platforms run one verified algorithm. Output is committed, so a Mac build
# does not need glslang/spirv-cross.
# Bindings: buffer(0)=FgConstants, sampler(1), texture(2..7)=t0..t5,
#           texture(8)=u0, buffer(7)=t5 structured, buffer(9)=u1 structured.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SH="$ROOT/native/framegen/shaders"
OUT="$ROOT/native/framegen-mac/Sources/SBFrameGenMac/GeneratedShaders.swift"
TMP="$(mktemp -d)"
{
  echo "// GENERATED by tools/gen_metal.sh from native/framegen/shaders/*.hlsl - do not edit."
  echo "enum GeneratedShaders {"
  echo "    static let sources: [String: String] = ["
  for f in "$SH"/*.hlsl; do
    n=$(basename "$f" .hlsl)
    glslangValidator -D -V -S comp -e main --hlsl-iomap --shift-UBO-binding 0 --shift-sampler-binding 1 \
      --shift-texture-binding 2 --shift-uav-binding 8 --shift-ssbo-binding 2 -o "$TMP/$n.spv" "$f" >/dev/null
    spirv-cross --msl --msl-version 20100 --msl-decoration-binding --rename-entry-point main "${n}_main" comp \
      "$TMP/$n.spv" --output "$TMP/$n.metal"
    echo "        \"$n\": #\"\"\""
    cat "$TMP/$n.metal"
    echo "\"\"\"#,"
  done
  echo "    ]"
  echo "}"
} > "$OUT"
rm -rf "$TMP"
echo "wrote $OUT"
